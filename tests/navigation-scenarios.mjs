import assert from 'node:assert/strict'
import { join } from 'node:path'
import { auditDesignSystem } from './design-system-audit.mjs'
import { switchProject, switchThread, openDeckImport } from './project-ui-helper.mjs'

export async function navigationScenarios(page, application, artifacts) {
  const ready = async () => {
    await page.waitForFunction(() => !document.querySelector('[data-nav-loading="true"]'))
    await page.evaluate(() => new Promise((resolve) => requestAnimationFrame(() => requestAnimationFrame(() => requestAnimationFrame(resolve)))))
  }
  const area = (name) => page.locator('.sidebar').getByRole('button', { name, exact: true })
  const back = page.getByRole('button', { name: 'Indietro', exact: true })
  const forward = page.getByRole('button', { name: 'Avanti', exact: true })
  await page.setViewportSize({ width: 1440, height: 900 })
  await ready()
  const feedback = page.getByLabel('Aggiungi un’osservazione')
  await feedback.fill('Bozza revisione: conservare la ricerca nel finale.')
  await page.locator('.discussion-history > summary').click()
  await page.locator('.discussion-version > summary').first().click()
  await page.locator('.guide-sources > summary').click()
  const link = page.locator('.strategy-field').first().getByRole('link', { name: 'Mega Absol ex', exact: true })
  await link.focus()
  await page.locator('.companion-list').evaluate((el) => { el.scrollTop = 175 })
  const before = await page.evaluate(() => ({ main: document.querySelector('.main-content').scrollTop, deck: document.querySelector('.companion-list').scrollTop }))
  await page.keyboard.press('Enter')
  await page.locator('.catalog-detail').getByRole('heading', { name: 'Mega Absol ex', exact: true }).waitFor()
  await ready()
  assert.match(await back.getAttribute('title'), /Gardevoir/)
  await page.keyboard.press('Alt+ArrowLeft')
  await ready()
  assert.equal(await feedback.inputValue(), 'Bozza revisione: conservare la ricerca nel finale.')
  assert.equal(await page.locator('.guide-sources').evaluate((el) => el.open), true)
  assert.equal(await page.locator('.discussion-history').evaluate((el) => el.open), true)
  assert.equal(await page.locator('.discussion-version').first().evaluate((el) => el.open), true)
  assert.ok(await link.evaluate((el) => el === document.activeElement), 'Il ritorno deve focalizzare il link di partenza')
  const after = await page.evaluate(() => ({ main: document.querySelector('.main-content').scrollTop, deck: document.querySelector('.companion-list').scrollTop }))
  assert.ok(Math.abs(after.main - before.main) < 3, `Scroll guida perso: ${JSON.stringify({ before, after })}`)
  assert.equal(after.deck, before.deck)
  await page.keyboard.press('Alt+ArrowRight')
  await ready()
  await page.getByLabel('Cerca carta o stampa').fill('Mega')
  await area('Impostazioni AI').click()
  await ready()
  await back.click()
  await ready()
  assert.equal(await page.getByLabel('Cerca carta o stampa').inputValue(), 'Mega', 'Filtro catalogo perso')
  await back.click()
  await ready()
  await area('Eventi').click()
  await ready()
  assert.ok(await forward.isDisabled(), 'Nuova navigazione dopo Indietro deve sostituire Avanti')
  await back.click()
  await ready()

  // The body external link does not add a page or modify the current view.
  const backTitle = await back.getAttribute('title')
  const external = page.locator('.strategy-field').first().getByRole('link', { name: 'lista campione', exact: true }).last()
  assert.equal(await external.locator('.external-link-mark').count(), 1)
  await external.click()
  assert.equal(await back.getAttribute('title'), backTitle)
  assert.ok(await feedback.isVisible() || await feedback.count() === 1)

  const seeded = await page.evaluate(async () => {
    const projects = await window.projectsApi.list()
    const project = projects.value.find((item) => item.name === 'Matchup · fixture UI')
    const baseline = await window.projectsApi.getBaseline(project.id)
    const threads = []
    for (const title of ['Navigazione A', 'Navigazione B']) {
      const result = await window.projectsApi.createDeckThread({ projectId: project.id, title })
      if (!result.ok) throw new Error(result.error)
      threads.push(result.value)
    }
    const candidate = await window.projectsApi.saveDeckCandidate({ projectId: project.id, threadId: threads[0].id, rawText: baseline.value.rawText, note: 'Candidata di esempio per navigazione' })
    if (!candidate.ok) throw new Error(candidate.error)
    return { projectId: project.id, threads }
  })
  await area('Thread').click()
  await ready()
  await switchThread(page, /Navigazione A/)
  await ready()
  const message = page.getByLabel('Scrivi nel thread')
  await message.fill('Bozza A da conservare')
  await page.getByRole('radio', { name: 'Proponi una lista', exact: true }).check()
  await page.locator('.candidate-comparison > summary').click()
  await area('Catalogo').click()
  await ready()
  await back.click()
  await ready()
  assert.equal(await message.inputValue(), 'Bozza A da conservare')
  assert.ok(await page.getByRole('radio', { name: 'Proponi una lista', exact: true }).isChecked())
  assert.ok(await page.locator('.candidate-comparison').evaluate((el) => el.open))
  await switchThread(page, /Navigazione B/)
  await ready()
  assert.equal(await message.inputValue(), '')
  await message.fill('Bozza B separata')
  await back.click()
  await ready()
  assert.equal(await message.inputValue(), 'Bozza A da conservare')
  await page.getByRole('button', { name: 'Salva osservazione', exact: true }).click()
  await page.waitForFunction(() => document.querySelector('#thread-message')?.value === '')
  await area('Catalogo').click()
  await ready()
  await back.click()
  await ready()
  assert.equal(await message.inputValue(), '', 'Indietro ha ripristinato un messaggio già salvato')
  assert.match(await page.locator('.thread-timeline').innerText(), /Bozza A da conservare/)
  // Delay a real local write: the new mount must remain busy, then refresh saved data.
  await application.evaluate(({ ipcMain }) => {
    const original = ipcMain._invokeHandlers.get('deck:add-thread-message')
    if (!original) throw new Error('Handler osservazioni mancante')
    globalThis.navigationMessageHandler = original
    ipcMain.removeHandler('deck:add-thread-message')
    ipcMain.handle('deck:add-thread-message', async (...args) => {
      await new Promise((resolve) => { globalThis.finishNavigationMessage = resolve })
      return original(...args)
    })
  })
  await message.fill('Salvataggio reale durante navigazione')
  await page.getByRole('button', { name: 'Salva osservazione', exact: true }).click()
  await page.waitForFunction(() => document.querySelector('#thread-message')?.disabled)
  await area('Catalogo').click()
  await ready()
  await back.click()
  await ready()
  assert.ok(await message.isDisabled(), 'La navigazione ha riabilitato un invio ancora in corso')
  await application.evaluate(() => globalThis.finishNavigationMessage())
  await page.waitForFunction(() => document.querySelector('#thread-message')?.value === '' && !document.querySelector('#thread-message')?.disabled)
  await page.getByText('Salvataggio reale durante navigazione', { exact: true }).waitFor()
  await application.evaluate(({ ipcMain }) => {
    ipcMain.removeHandler('deck:add-thread-message')
    ipcMain.handle('deck:add-thread-message', globalThis.navigationMessageHandler)
  })
  await switchProject(page, /Progetto separato/)
  await ready()
  assert.equal(await page.locator('.thread-timeline').count(), 0, 'Contenuti di un altro progetto visibili')
  await back.click()
  await ready()
  assert.match(await page.locator('#thread-switcher-trigger').innerText(), /Navigazione A/)

  await area('Lista').click()
  await ready()
  const absol = page.getByTestId('deck-card-fixture-absol')
  await absol.locator('.deck-card-toggle').click()
  await absol.getByRole('button', { name: 'Aggiungi vincolo su questa carta', exact: true }).click()
  await absol.getByLabel('Tipo di vincolo').selectOption('minimum')
  await absol.getByLabel('Numero di copie').fill('3')
  await area('Catalogo').click()
  await ready()
  await back.click()
  await ready()
  assert.equal(await absol.getByLabel('Tipo di vincolo').inputValue(), 'minimum')
  assert.equal(await absol.getByLabel('Numero di copie').inputValue(), '3')
  await absol.locator('.constraint-form').getByRole('button', { name: 'Aggiungi vincolo', exact: true }).click()
  await absol.getByText('Vincolo aggiunto.', { exact: true }).waitFor()
  const constraints = await page.evaluate((projectId) => window.projectsApi.listConstraints(projectId), seeded.projectId)
  assert.equal(constraints.ok, true)
  assert.equal(constraints.value.length, 1)
  assert.equal(constraints.value[0].quantity, 3)
  await openDeckImport(page)
  await page.getByLabel('Testo lista').fill('1 Mega Absol ex MEG 86\nTotal Cards: 1')
  await area('Eventi').click()
  await ready()
  await back.click()
  await ready()
  assert.equal(await page.getByLabel('Testo lista').inputValue(), '1 Mega Absol ex MEG 86\nTotal Cards: 1')
  await page.getByRole('button', { name: 'Annulla', exact: true }).click()
  const actual = await page.evaluate(async (projectId) => (await window.projectsApi.getBaseline(projectId)).value.interpretedTotal, seeded.projectId)
  assert.equal(actual, 60, 'Navigare non deve salvare né annullare modifiche al mazzo')

  // Returning while a read is pending must never paint the abandoned Catalog in Matchup.
  await application.evaluate(({ ipcMain }) => {
    const original = ipcMain._invokeHandlers.get('catalog:browse-overview')
    globalThis.navigationCatalogHandler = original
    if (original) { ipcMain.removeHandler('catalog:browse-overview'); ipcMain.handle('catalog:browse-overview', async (...args) => { await new Promise((resolve) => setTimeout(resolve, 600)); return original(...args) }) }
  })

  // Simulated unavailable destination; no production data is deleted.
  await area('Thread').click()
  await ready()
  await area('Catalogo').click()
  await ready()
  await application.evaluate(({ ipcMain }, missingId) => {
    const original = ipcMain._invokeHandlers.get('deck:list-thread-summaries')
    if (!original) throw new Error('Handler thread mancante')
    globalThis.navigationThreadHandler = original
    ipcMain.removeHandler('deck:list-thread-summaries')
    ipcMain.handle('deck:list-thread-summaries', async (...args) => {
      const result = await original(...args)
      return result.ok ? { ...result, value: result.value.filter((item) => item.id !== missingId) } : result
    })
  }, seeded.threads[0].id)
  await back.click()
  await ready()
  await page.getByRole('alert').filter({ hasText: 'Il thread non è più disponibile' }).waitFor()
  assert.equal(await page.locator('.thread-timeline').count(), 0)
  await application.evaluate(({ ipcMain }) => {
    ipcMain.removeHandler('deck:list-thread-summaries')
    ipcMain.handle('deck:list-thread-summaries', globalThis.navigationThreadHandler)
  })
  await area('Matchup').click()
  await ready()
  await area('Catalogo').click()
  await back.click()
  await ready()
  assert.equal(await page.locator('.catalog-section').count(), 0)
  assert.match(await page.locator('#matchup-switcher-trigger').innerText(), /Gardevoir/)
  await application.evaluate(({ ipcMain }) => {
    if (globalThis.navigationCatalogHandler) { ipcMain.removeHandler('catalog:browse-overview'); ipcMain.handle('catalog:browse-overview', globalThis.navigationCatalogHandler) }
  })

  for (const [width, height] of [[1440, 900], [1280, 720], [640, 720]]) {
    await page.setViewportSize({ width, height })
    await page.locator('.main-content').evaluate((el) => { el.scrollTop = 0 })
    const boxes = await page.evaluate(() => {
      const rect = (selector) => { const r = document.querySelector(selector).getBoundingClientRect(); return { left: r.left, right: r.right, top: r.top, bottom: r.bottom } }
      return { controls: rect('.history-controls'), header: rect('.topbar'), deck: rect('.deck-companion'), main: rect('.main-content'), overflow: document.documentElement.scrollWidth > innerWidth }
    })
    assert.ok(boxes.controls.left >= boxes.header.left && boxes.controls.right <= boxes.header.right)
    assert.ok(boxes.controls.top >= 0 && boxes.controls.bottom <= boxes.header.bottom)
    assert.equal(boxes.overflow, false)
    assert.ok(width > 1240 ? boxes.main.right <= boxes.deck.left : boxes.main.bottom <= boxes.deck.top)
    await back.focus()
    assert.ok(await back.evaluate((el) => el === document.activeElement))
    await auditDesignSystem(page, `Navigazione ${width}`)
    await page.screenshot({ path: join(artifacts, `navigation-${width}.png`) })
  }
  // Leave the surrounding selector regression in its expected, closed state.
  await page.locator('.guide-sources').evaluate((el) => { el.open = false })
  await page.locator('.discussion-history').evaluate((el) => { el.open = false })
  console.log('NAVIGATION OK: back/forward, focus, independent scrolls, revisions, filters, drafts, saved/pending messages, projects, unavailable destination, late reads, branching, external links; 1440/1280/640')
}
